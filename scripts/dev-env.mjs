// 로컬 개발 환경(.env)·로컬 전용 DB 가드 공용 도우미(scripts/dev-db.mjs, scripts/dev-local.mjs)
// - .env가 없으면 .env.example을 바탕으로 로컬 전용 비밀값·계정 비밀번호를 채워 만든다(.env는 gitignore).
// - DATABASE_URL의 호스트가 127.0.0.1 / localhost / ::1이 아니면 즉시 중단해 NAS·원격 DB를 보호한다.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const ENV_PATH = path.join(REPO_ROOT, ".env");
export const ENV_EXAMPLE_PATH = path.join(REPO_ROOT, ".env.example");
const LOCAL_HOSTS = new Set(["127.0.0.1", "localhost", "::1"]);

/** .env 텍스트 → 키/값 객체(간단한 KEY=VALUE, 주석·빈 줄 무시) */
export function parseEnvText(text) {
  const out = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

/** .env가 없으면 .env.example을 채워 만든다(이미 있으면 건드리지 않음) */
export function ensureLocalEnv() {
  if (!existsSync(ENV_PATH)) {
    const template = readFileSync(ENV_EXAMPLE_PATH, "utf8");
    const user = os.userInfo().username || "postgres";
    const secret = randomBytes(32).toString("hex");
    const password = `TerraDev_${randomBytes(6).toString("hex")}`;
    const filled = template
      .replaceAll("<OS_USER>", user)
      .replaceAll("<auto-generated-64-hex>", secret)
      .replaceAll("<auto-generated-password>", password);
    writeFileSync(ENV_PATH, filled, { encoding: "utf8", mode: 0o600 });
    console.log(`✓ .env 생성 완료 (${ENV_PATH})`);
  }
  const parsed = parseEnvText(readFileSync(ENV_PATH, "utf8"));
  return { ...parsed, ...process.env };
}

/** NAS·외부 DB 보호: DATABASE_URL 호스트가 로컬이 아니면 거부 */
export function assertLocalDatabaseUrl(rawUrl) {
  if (!rawUrl) {
    throw new Error("DATABASE_URL이 비어 있습니다. .env의 DATABASE_URL을 확인하세요.");
  }
  let parsed;
  try {
    parsed = new URL(rawUrl);
  } catch {
    throw new Error(`DATABASE_URL 형식이 올바르지 않습니다: ${rawUrl}`);
  }
  const host = parsed.hostname.replace(/^\[|\]$/g, "");
  if (!LOCAL_HOSTS.has(host)) {
    throw new Error(
      `안전 차단: 로컬 개발 스크립트는 127.0.0.1 / localhost DB만 허용합니다(현재 호스트: ${host}).`,
    );
  }
  const dbName = parsed.pathname.replace(/^\//, "");
  if (!dbName || !/^[a-zA-Z0-9_]+$/.test(dbName)) {
    throw new Error(`로컬 DB 이름 형식이 올바르지 않습니다: ${dbName || "(없음)"}`);
  }
  return { url: parsed, dbName, host, port: parsed.port || "5432" };
}

/** apps/server의 pg 드라이버를 가져온다(루트 package.json 의존성 추가 없이) */
export function loadPg() {
  const req = createRequire(path.join(REPO_ROOT, "apps/server/package.json"));
  return req("pg");
}
